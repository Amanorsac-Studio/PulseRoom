#!/usr/bin/env node
/* Bundle the answer files into the app.
 *
 * Emits answers.js rather than answers.json on purpose: Electron loads the app
 * from file://, where fetch() of a sibling JSON file is blocked, and the page's
 * CSP is script-src 'self'. A plain script that assigns a global works in
 * Electron, in the Capacitor WebView on both phones, and over http in the
 * browser preview, with no loader and no network path.
 *
 * The search index is NOT precomputed. Building it at startup from 700 entries
 * costs a couple of milliseconds and removes a whole class of stale-index bugs.
 *
 *   npm run answers
 */
'use strict';

const fs = require('fs');
const path = require('path');

const DATA = path.join(__dirname, '..', 'v2', 'data');
const OUT = path.join(__dirname, '..', 'answers.js');

/* Files that hold finished answers. The backlog files (question-index,
   playbooks, concepts) hold questions without answers and are not shipped. */
const BACKLOG = new Set(['question-index.json', 'playbooks.json', 'concepts.json']);

const files = fs.readdirSync(DATA).filter(f => f.endsWith('.json') && !BACKLOG.has(f)).sort();

const out = [];
const seen = new Map();
let errors = 0;

for (const file of files) {
  const doc = JSON.parse(fs.readFileSync(path.join(DATA, file), 'utf8'));
  for (const q of doc.questions || []) {
    if (!q.short || !q.steps) continue;            // backlog row that slipped in

    if (seen.has(q.id)) {
      console.error(`  ERROR duplicate id "${q.id}" in ${file} and ${seen.get(q.id)}`);
      errors++;
      continue;
    }
    seen.set(q.id, file);

    // ship only what the app renders, so the bundle stays small
    out.push({
      id: q.id, q: q.q, a: q.aliases || [],
      src: q.source, intent: q.intent, g: q.genres || ['all'],
      short: q.short, steps: q.steps,
      params: q.params || {},
      viz: (q.visual && q.visual.type) || 'eq-curve',
      why: q.why, watch: q.watch || '',
      notes: q.genreNotes || null,
      rel: q.related || []
    });
  }
}

if (errors) { console.error(`\n${errors} error(s) — nothing written`); process.exit(1); }

const bytes = JSON.stringify(out).length;
fs.writeFileSync(OUT,
  `/* Generated by scripts/build-answers.js — do not edit.\n` +
  `   ${out.length} answers from ${files.length} files, ${(bytes / 1024).toFixed(0)} KB. */\n` +
  `window.PR_ANSWERS = ${JSON.stringify(out)};\n`);

const bySrc = out.reduce((m, q) => (m[q.src] = (m[q.src] || 0) + 1, m), {});
console.log(`${out.length} answers from ${files.length} files -> answers.js (${(bytes / 1024).toFixed(0)} KB)`);
console.log(`${Object.keys(bySrc).length} sources covered`);
